"""Create a clearly labelled demo account by running the REAL services (live AI when configured).

    python -m app.demo                 # creates identifier "demo.priya" (refuses if it exists)
    python -m app.demo --reset         # deletes and recreates it — only if that account is flagged is_demo

Nothing is hardcoded as AI output: the JD, resume, short answers and interview answer below are fictional *inputs*;
all extraction, scoring, gaps, plans and feedback are generated by the normal pipeline. The account is marked
is_demo=true and never touches any other user's data.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

from sqlalchemy import delete, select

from app.ai.gateway import get_gateway
from app.core.db import session_factory
from app.core.timeutil import user_today
from app.models import Question, User
from app.modules import hooks
from app.modules.assessments import service as assessments
from app.modules.assessments.scoring import validate_response
from app.modules.auth.service import DemoIdentifierAuth
from app.modules.interviews import service as interviews
from app.modules.plans import service as plans
from app.modules.resumes import service as resumes
from app.modules.targets import service as targets
from app.modules.targets.requirements import load_requirements

DEMO_ID = "demo.priya"
DEMO_DIR = Path(__file__).resolve().parents[2] / "demo"
INTERVIEW_ANSWER = (
    "A transaction groups several statements so they either all commit or all roll back. For a transfer we debit one "
    "account and credit another; if the server crashed after the debit but before the credit, money would disappear. "
    "Inside a transaction that partial state is never visible, and with row locks or a suitable isolation level two "
    "concurrent transfers cannot both spend the same balance."
)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--reset", action="store_true")
    args = ap.parse_args()
    gw = get_gateway()
    print(f"AI provider: {'enabled' if gw.available else 'DISABLED (deterministic fallbacks will be used)'}")
    with session_factory()() as db:
        existing = db.scalar(select(User).where(User.identifier == DEMO_ID))
        if existing is not None:
            if not args.reset:
                print(f"'{DEMO_ID}' already exists. Use --reset to recreate it.")
                return 1
            if not existing.is_demo:
                print(f"Refusing: '{DEMO_ID}' is a real (non-demo) account.")
                return 2
            db.execute(delete(User).where(User.id == existing.id, User.is_demo.is_(True)))
            db.commit()
        user, _ = DemoIdentifierAuth().authenticate(db, {"identifier": DEMO_ID})
        user.is_demo, user.preferred_name, user.experience_level = True, "Priya (demo)", "fresher"
        db.commit()
        today = user_today(user.timezone)

        t = targets.create_target(db, user, role_slug="backend-dev", job_title="Backend Engineer – Fresher",
                                  company_name="Northwind Fintech", deadline_date=None, daily_minutes=90,
                                  archive_current=True, today=today)
        jd, warnings = targets.submit_job_description(db, user, t, (DEMO_DIR / "sample_jd.txt").read_text(), False, gw)
        print(f"JD: {jd.status} {warnings}")
        reqs = [{"id": str(r.id), "skill_slug": r.skill_slug, "raw_phrase": r.raw_phrase,
                 "requirement_level": r.level, "category": r.category} for r in load_requirements(db, t)]
        targets.replace_requirements(db, user, t, reqs, None)
        hooks.requirements_changed(db, user, t, "requirements_changed")

        r, v, res = resumes.import_text(db, user, (DEMO_DIR / "sample_resume.txt").read_text(), title="Demo resume",
                                        source="paste", filename=None, gateway=gw)
        content = resumes.ResumeContent.model_validate(v.content)
        resumes.save_version(db, user, r, content, v.id, change_summary="Reviewed after import", mark_reviewed=True)
        hooks.resume_changed(db, user, db.get(type(r), r.id))
        print(f"Resume: {res.status}, {len(content.projects)} projects, {len(content.experience)} experience")

        # Diagnostic: answer right on some skills, wrong on SQL — scored by the real pipeline.
        a = assessments.start(db, user, t, "diagnostic", None)
        for item, q, skill in assessments.items_with_questions(db, a):
            if q.options:
                right = q.correct_answer["selected"]
                wrong = [o["id"] for o in q.options if o["id"] not in right][:1]
                resp = {"selected": wrong if skill.slug == "sql" else right}
            else:
                resp = {"text": q.reference_answer or ""}
            item.response = validate_response(item.type, q.options, resp)
        db.commit()
        a = assessments.submit(db, user, a, gw)
        plans.complete_linked_tasks(db, user, t, "assess", None, a.id)
        hooks.evidence_changed(db, user, t, "assessment_scored")
        print(f"Diagnostic: {a.status}, score {a.score}")

        plan = plans.generate(db, user, t)
        print(f"Plan revision {plan.revision}")

        s = interviews.start(db, user, t, "technical", "sql")
        turn = s and db.scalars(select(interviews.InterviewTurn).where(interviews.InterviewTurn.session_id == s.id)).first()
        if turn is not None:
            q = db.get(Question, turn.question_id) if turn.question_id else None
            answer = INTERVIEW_ANSWER if q is None or "transaction" in q.prompt.lower() else (q.reference_answer or INTERVIEW_ANSWER)
            interviews.submit_answer(db, user, s, turn, answer, "typed", gw)
            hooks.evidence_changed(db, user, t, "interview")
            print(f"Interview: {turn.evaluation_status}, overall {turn.overall_score}")
        user.onboarding_step, user.onboarding_completed_at = 5, user.onboarding_completed_at or user.created_at
        db.commit()
    print(f"Done. Log in with the identifier '{DEMO_ID}'. This account is flagged as demo data.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
